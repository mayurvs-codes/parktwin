/**
 * Physical Camera Groups — groups all 33 recording segments by physical recorder channel.
 * (Cameras 3, 5, 6, 7, 8, 9, 10, 11, 14, 15, 16, 19, 20, 21, 22, 24)
 */
export function getPhysicalCameraGroups(): PhysicalCameraGroup[] {
  const groupMap = new Map<number, RealArchiveSegment[]>();

  REAL_ARCHIVE_SEGMENTS.forEach((seg) => {
    const list = groupMap.get(seg.physicalCameraNum) || [];
    list.push(seg);
    groupMap.set(seg.physicalCameraNum, list);
  });

  const sortedCamNums = Array.from(groupMap.keys()).sort((a, b) => a - b);

  return sortedCamNums.map((camNum) => {
    const segs = groupMap.get(camNum) || [];
    const totalBytes = segs.reduce((acc, s) => acc + s.fileSizeBytes, 0);
    const totalMb = (totalBytes / (1024 * 1024)).toFixed(2);
    const firstStart = segs[0]?.startTime || "15:45:00";
    const lastEnd = segs[segs.length - 1]?.endTime || "17:00:00";

    return {
      physicalCameraNum: camNum,
      physicalCameraId: `IP Camera ${camNum}`,
      parkTwinCameraId: null,
      mappingStatus: "UNVERIFIED",
      segments: segs,
      totalSizeBytes: totalBytes,
      totalSizeLabel: `${totalMb} MB`,
      timeCoverage: `${firstStart} → ${lastEnd}`,
      facility: segs[0]?.facility || "Carparking-01",
    };
  });
}
